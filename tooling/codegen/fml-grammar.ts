// Generates the TypeScript parser of the official FML grammar with antlr-ng (ADR-0008).
// The output is committed in packages/fml/src/grammar/generated and checked for drift by
// fml-grammar.test.ts; regenerate it with `pnpm codegen`.
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, rmSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../../", import.meta.url));

export const GRAMMAR_FILE = "packages/fml/grammar/mapping.g4";
export const OUTPUT_DIR = "packages/fml/src/grammar/generated";
/** Only the lexer and the parser are needed at run time: no listener, no visitor. */
export const OUTPUT_FILES = ["mappingLexer.ts", "mappingParser.ts"] as const;

function antlrNgVersion(): string {
  const pkg = JSON.parse(readFileSync(`${root}node_modules/antlr-ng/package.json`, "utf8")) as {
    version: string;
  };
  return pkg.version;
}

/** Header that marks the files as generated; no timestamps, so the output stays deterministic. */
export function header(version: string): string {
  return [
    `// Generated by antlr-ng ${version} from ${GRAMMAR_FILE} (ADR-0008).`,
    "// Do not edit: run `pnpm codegen`.",
    "",
  ].join("\n");
}

/** Runs antlr-ng into a scratch directory under .tmp/ and returns the generated files by name. */
export function generateGrammarParser(): Map<string, string> {
  const scratch = `${root}.tmp/codegen/fml-grammar`;
  rmSync(scratch, { recursive: true, force: true });
  mkdirSync(scratch, { recursive: true });
  execFileSync(
    `${root}node_modules/.bin/antlr-ng`,
    [
      "-Dlanguage=TypeScript",
      "--generate-listener",
      "false",
      "-o",
      scratch,
      `${root}${GRAMMAR_FILE}`,
    ],
    { stdio: ["ignore", "ignore", "inherit"] },
  );
  const head = header(antlrNgVersion());
  return new Map(
    OUTPUT_FILES.map((file) => [file, head + readFileSync(`${scratch}/${file}`, "utf8")]),
  );
}
