import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import {
  GRAMMAR_FILE,
  OUTPUT_DIR,
  OUTPUT_FILES,
  generateGrammarParser,
  header,
} from "./fml-grammar.ts";

const root = fileURLToPath(new URL("../../", import.meta.url));

describe("FML grammar parser", () => {
  it("uses the pinned grammar, byte-identical to fixtures/fml-examples (HL7 commit 8bb04b4)", () => {
    expect(readFileSync(`${root}${GRAMMAR_FILE}`, "utf8")).toBe(
      readFileSync(`${root}fixtures/fml-examples/grammar/mapping.g4`, "utf8"),
    );
  });

  // Drift check: the committed parser must be exactly what antlr-ng generates from the grammar.
  it("is up to date (run `pnpm codegen` if this fails)", () => {
    const generated = generateGrammarParser();
    expect([...generated.keys()]).toEqual([...OUTPUT_FILES]);
    for (const [file, source] of generated) {
      expect(readFileSync(`${root}${OUTPUT_DIR}/${file}`, "utf8"), file).toBe(source);
    }
  }, 60_000);

  it("marks the files as generated without timestamps", () => {
    expect(header("1.2.3")).toBe(
      "// Generated by antlr-ng 1.2.3 from packages/fml/grammar/mapping.g4 (ADR-0008).\n// Do not edit: run `pnpm codegen`.\n",
    );
  });
});
